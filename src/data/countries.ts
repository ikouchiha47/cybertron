/**
 * Case-insensitive country search.
 *
 * A blank query returns the full list. Otherwise a country matches when its name
 * contains the query (case-insensitive) or its ISO code starts with the query.
 */
export function findCountries(query: string): Country[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...COUNTRIES];
  return COUNTRIES.filter(
    (c) => c.name.toLowerCase().includes(q) || c.code.toLowerCase().startsWith(q),
  );
}
